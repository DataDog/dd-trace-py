#!/usr/bin/env python3
"""Run normal pytest --ddtrace sessions against staging using the active Python.

Requires Python 3.12+ with pytest and this branch's ddtrace installed.
Set DD_API_KEY below or in the environment. --prepare-only creates the corpus
and prints a command for running pytest manually, without contacting staging.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shlex
import shutil

# This developer driver intentionally executes Git and the selected Python interpreter.
import subprocess  # nosec B404
import sys
import tempfile
import uuid

# JUnit input is generated by this driver in its own synthetic repository.
import xml.etree.ElementTree as ET  # nosec B405


# Set this locally, or export DD_API_KEY before running the script.
DD_API_KEY = ""
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from tests.testing.internal.pytest.tia_corpus import write_corpus  # noqa: E402


PYTEST_ARGS = ("--ddtrace", "-q", "--junitxml=.artifacts/junit.xml", "tests")


def git(root: Path, *args: str) -> str:
    executable = shutil.which("git")
    if executable is None:
        raise RuntimeError("git must be installed and available on PATH")
    # The executable is resolved locally and all arguments are passed without a shell.
    return subprocess.check_output([executable, *args], cwd=root, text=True, stderr=subprocess.STDOUT).strip()  # nosec B603


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--python", default=sys.executable, help="Python 3.12+ with pytest and this branch's ddtrace installed"
    )
    parser.add_argument("--prepare-only", action="store_true", help="Create the corpus for manual pytest runs")
    args = parser.parse_args()
    api_key = os.environ.get("DD_API_KEY") or DD_API_KEY.strip()
    if not args.prepare_only and not api_key:
        parser.error("Set DD_API_KEY in the environment or near the top of this script")

    output_root = ROOT / ".cache/tia-staging"
    output_root.mkdir(parents=True, exist_ok=True)
    output = Path(tempfile.mkdtemp(prefix="run-", dir=output_root))
    project = output / "project"
    project.mkdir()
    write_corpus(project)
    git(project, "init", "--initial-branch=main")
    # These identities and unsigned commits belong only to the disposable synthetic repository.
    git(project, "config", "user.name", "TIA staging corpus")
    git(project, "config", "user.email", "tia-staging@example.test")
    git(project, "config", "commit.gpgsign", "false")
    git(project, "remote", "add", "origin", f"https://example.test/tia-staging/{uuid.uuid4().hex}.git")
    git(project, "add", ".")
    git(project, "commit", "-m", "Initial shop corpus")
    print(f"Corpus: {project}", flush=True)
    print(f"Logs and summary: {output}", flush=True)
    if args.prepare_only:
        print(f"\ncd {shlex.quote(str(project))}")
        print(
            "DD_API_KEY=... DD_SITE=datad0g.com DD_TIA_ENABLED=1 "
            f"DD_CIVISIBILITY_AGENTLESS_ENABLED=1 {shlex.quote(args.python)} -m pytest --ddtrace tests"
        )
        return 0

    env = os.environ.copy()
    # Remove inherited CI identity and endpoint overrides so Git and DD_SITE describe this corpus.
    for name in list(env):
        if name.startswith(("_CI_DD_", "DD_GIT_")) or name in (
            "DD_CIVISIBILITY_AGENTLESS_URL",
            "DD_APPLICATION_KEY",
            "PYTEST_ADDOPTS",
            "PYTEST_PLUGINS",
        ):
            env.pop(name)
    env.update(
        {
            "DD_API_KEY": api_key,
            "DD_SITE": "datad0g.com",
            "DD_TIA_ENABLED": "1",
            # DD_SITE alone does not select direct API-key transport.
            "DD_CIVISIBILITY_AGENTLESS_ENABLED": "1",
            "DD_SERVICE": "tia-staging-e2e",
            # Keep unrelated retry features from changing the expected failure counts.
            "DD_CIVISIBILITY_EARLY_FLAKE_DETECTION_ENABLED": "0",
            "DD_CIVISIBILITY_FLAKY_RETRY_ENABLED": "0",
            "DD_TEST_MANAGEMENT_ENABLED": "0",
            "DD_CIVISIBILITY_GIT_UPLOAD_ENABLED": "0",
            "DD_CIVISIBILITY_GIT_UNSHALLOW_ENABLED": "0",
        }
    )
    # The user selects the Python executable; its arguments are fixed.
    preflight = subprocess.run(  # nosec B603
        [
            args.python,
            "-c",
            "import sys; assert sys.version_info >= (3, 12), 'Python 3.12+ is required'; "
            "import pytest, ddtrace; from ddtrace.testing.internal.pytest._tia import TIAPlugin; "
            "print('Python:', sys.version.split()[0]); print('Using ddtrace:', ddtrace.__file__)",
        ],
        cwd=project,
        env=env,
        capture_output=True,
        text=True,
    )
    if preflight.returncode:
        parser.error(
            "Selected Python must be 3.12+ with pytest and this branch's ddtrace installed. "
            "Activate that environment or pass --python /path/to/venv/bin/python"
        )
    print(preflight.stdout, end="", flush=True)
    command = [args.python, "-m", "pytest", *PYTEST_ARGS]
    process_test = "tests/test_process.py::test_child"
    carts = {"tests/test_cart.py::test_add[1]", "tests/test_cart.py::test_add[2]"}
    settings = {"tests/test_static.py::test_static", "tests/test_dynamic.py::test_dynamic"}
    all_tests = (
        carts
        | settings
        | {
            process_test,
            "tests/test_shipping.py::test_fee",
            "tests/test_threads.py::test_stock",
            "tests/test_smoke.py::test_smoke",
        }
    )
    phases: list[dict[str, object]] = []

    def run(label: str, root: Path, selected: set[str], failures: int = 0) -> None:
        print(
            f"\n=== {label} ===\n$ DD_API_KEY=<redacted> DD_SITE=datad0g.com DD_TIA_ENABLED=1 "
            f"DD_CIVISIBILITY_AGENTLESS_ENABLED=1 {shlex.join(command)}",
            flush=True,
        )
        result = subprocess.run(command, cwd=root, env=env, capture_output=True, text=True, timeout=180)  # nosec B603
        for stream in ("stdout", "stderr"):
            content = getattr(result, stream).replace(api_key, "<redacted>")
            (output / f"{label}.{stream}").write_text(content)
            print(content, end="", flush=True)
        if result.returncode != (1 if failures else 0):
            raise RuntimeError(f"{label}: unexpected pytest exit code {result.returncode}; see {output}")
        report = ET.parse(root / ".artifacts/junit.xml")  # nosec B314: driver-generated JUnit data
        executed = {
            f"{case.attrib['classname'].replace('.', '/')}.py::{case.attrib['name']}"
            for case in report.iter("testcase")
        }
        if executed != selected or len(list(report.iter("failure"))) != failures:
            raise RuntimeError(
                f"{label}: expected {sorted(selected)} with {failures} failures, got {sorted(executed)}; see {output}"
            )
        if git(root, "status", "--porcelain"):
            raise RuntimeError(f"{label}: corpus became dirty")
        phases.append(
            {
                "phase": label,
                "selected": sorted(executed),
                "failed": failures,
                "deselected": len(all_tests) - len(executed),
            }
        )
        (output / "summary.json").write_text(json.dumps(phases, indent=2))

    def change(path: str, source: str, message: str) -> None:
        (project / path).write_text(source)
        git(project, "add", path)
        git(project, "commit", "-m", message)

    run("initial_recording", project, all_tests)
    maps = list((project / ".git/.testoptimization/tia").glob("*/*.json"))
    if len(maps) != 1:
        raise RuntimeError(f"No dependency map recorded; check {output}")
    (output / "map.json").write_bytes(maps[0].read_bytes())
    run("unchanged_local_map", project, {process_test})
    change("shop/cart.py", "def items(quantity): return list(range(quantity + 1))\n", "Break cart")
    run("affected_cart_failures", project, carts | {process_test}, 2)
    run("unchanged_failed_tests", project, carts | {process_test}, 2)
    change("shop/cart.py", "def items(quantity): return [n for n in range(quantity)]\n", "Fix cart")
    clone = output / "fresh-checkout"
    git(output, "clone", "--local", str(project), str(clone))
    # A clone has no local TIA cache. Correct selection here requires the staging artifact lookup.
    run("fresh_clone_remote_map", clone, carts | {process_test})
    run("cart_recovery", project, carts | {process_test})
    change("shop/settings.py", "VALUE = 2\n", "Break cached import")
    run("cached_dynamic_import", project, settings | {process_test}, 2)
    change("shop/settings.py", "VALUE = 1\nVERSION = 2\n", "Fix cached import")
    run("dynamic_import_recovery", project, settings | {process_test})
    change("shop/currency.py", "UNIT = 'EUR'\n", "Break shared fixture")
    run("shared_fixture_failures", project, all_tests, 3)
    change("shop/currency.py", "UNIT = 'USD'\nVERSION = 2\n", "Fix shared fixture")
    run("shared_fixture_recovery", project, all_tests)
    print(f"\nAll pytest scenarios passed. Results: {output}", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
