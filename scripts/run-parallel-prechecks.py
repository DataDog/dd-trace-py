#!/usr/bin/env python3
"""Run the CI prechecks in parallel.

Reads a check list where each non-blank line is a JSON object:
{"name": "...", "command": "..."}. Every check runs in its own subprocess with
its output captured. Once all checks have finished, the logs are printed in
the original list order as collapsible GitLab sections (failed checks are
left expanded), followed by a summary table. All checks always run to
completion before exiting, so one failure does not hide the others; the
script exits non-zero if any check failed.

Usage:
  scripts/run-parallel-prechecks.py [CHECKS_FILE]

CHECKS_FILE defaults to "-" (read the check list from stdin).
"""

from __future__ import annotations

import argparse
import concurrent.futures
from dataclasses import dataclass
import json
import subprocess  # nosec B404
import sys
import time
from typing import IO


@dataclass
class CheckResult:
    name: str
    output: str
    returncode: int
    duration: float


def parse_checks(stream: IO[str]) -> list[tuple[str, str]]:
    """Read one JSON check object per line: {"name": ..., "command": ...}."""
    checks: list[tuple[str, str]] = []
    for line in stream:
        line = line.strip()
        if not line:
            continue
        try:
            entry = json.loads(line)
        except json.JSONDecodeError as e:
            raise ValueError(f"malformed check line (invalid JSON): {line!r}") from e
        if (
            not isinstance(entry, dict)
            or set(entry) != {"name", "command"}
            or not all(isinstance(entry[key], str) and entry[key] for key in ("name", "command"))
        ):
            raise ValueError(f'malformed check line (expected {{"name": ..., "command": ...}}): {line!r}')
        checks.append((entry["name"], entry["command"]))
    return checks


def run_check(name: str, command: str) -> CheckResult:
    """Run one check, capturing its combined stdout/stderr and wall time."""
    start = time.monotonic()
    # The command comes from the check list generated by
    # scripts/gen_gitlab_config.py, not from user input.
    proc = subprocess.run(  # nosec B602
        command, shell=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT
    )
    duration = time.monotonic() - start
    return CheckResult(name, proc.stdout.decode(errors="replace"), proc.returncode, duration)


def print_result(index: int, result: CheckResult) -> None:
    """Print one buffered check log as a GitLab collapsible section."""
    status = "PASS" if result.returncode == 0 else "FAIL"
    collapsed = "[collapsed=true]" if result.returncode == 0 else ""
    timestamp = int(time.time())
    print(
        f"\x1b[0Ksection_start:{timestamp}:check_{index}{collapsed}\r\x1b[0K"
        f"{result.name}: {status} in {result.duration:.0f}s",
        flush=True,
    )
    sys.stdout.write(result.output)
    if result.output and not result.output.endswith("\n"):
        print()
    print(f"\x1b[0Ksection_end:{timestamp}:check_{index}\r\x1b[0K", flush=True)


def print_summary(results: list[CheckResult]) -> None:
    print()
    print("Precheck summary:")
    for result in results:
        status = "PASS" if result.returncode == 0 else "FAIL"
        print(f"  {status:<4} {result.duration:>4.0f}s  {result.name}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "checks_file",
        nargs="?",
        default="-",
        help="file with name<TAB>command lines, or - for stdin (default)",
    )
    args = parser.parse_args(argv)

    try:
        if args.checks_file == "-":
            checks = parse_checks(sys.stdin)
        else:
            with open(args.checks_file) as f:
                checks = parse_checks(f)
    except OSError as e:
        print(f"run-parallel-prechecks: cannot read checks file: {e}", file=sys.stderr)
        return 2
    except ValueError as e:
        print(f"run-parallel-prechecks: {e}", file=sys.stderr)
        return 2

    if not checks:
        return 0

    # One thread per check: the threads only wait on subprocesses, so
    # launching them all matches the previous background-process behavior.
    with concurrent.futures.ThreadPoolExecutor(max_workers=len(checks)) as pool:
        futures = [pool.submit(run_check, name, command) for name, command in checks]
        results = [future.result() for future in futures]

    for index, result in enumerate(results):
        print_result(index, result)
    print_summary(results)

    if any(result.returncode != 0 for result in results):
        print("One or more prechecks failed.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
