"""
The pytest integration traces test executions.

Enabling
~~~~~~~~

Enable traced execution of tests using ``pytest`` runner by
running ``pytest --ddtrace`` or by modifying any configuration
file read by pytest (``pytest.ini``, ``setup.cfg``, ...)::

    [pytest]
    ddtrace = 1


If you need to disable it, the option ``--no-ddtrace`` will take
precedence over ``--ddtrace`` and (``pytest.ini``, ``setup.cfg``, ...)

You can enable all integrations by using the ``--ddtrace-patch-all`` option
alongside ``--ddtrace`` or by adding this to your configuration::

    [pytest]
    ddtrace = 1
    ddtrace-patch-all = 1


.. note::
   The ddtrace plugin for pytest has the side effect of importing the ddtrace
   package and starting a global tracer.

   If this is causing issues for your pytest runs where traced execution of
   tests is not enabled, you can deactivate the plugin::

     [pytest]
     addopts = -p no:ddtrace

   See the `pytest documentation
   <https://docs.pytest.org/en/7.1.x/how-to/plugins.html#deactivating-unregistering-a-plugin-by-name>`_
   for more details.


Test automation exclusions
~~~~~~~~~~~~~~~~~~~~~~~~~~

Import ``prevent_failure_suppression`` and ``no_auto_retry`` from ``ddtrace.testing``
and decorate individual pytest test functions or methods::

    from ddtrace.testing import no_auto_retry, prevent_failure_suppression

    @prevent_failure_suppression
    @no_auto_retry
    def test_critical_behavior():
        assert check_critical_behavior()

``prevent_failure_suppression`` overrides Datadog quarantine and disabling. It does
not disable retries or change pytest expected-failure behavior. ``no_auto_retry``
excludes Datadog Auto Test Retries, Early Flake Detection, and Attempt to Fix;
explicit retries from pytest retry plugins remain available. Both decorators apply
to every case generated by ``pytest.mark.parametrize`` and preserve developer skips,
filters, and Test Impact Analysis selection. Backend management assignments remain
reported even when their execution policy is overridden. Each decorator returns a
separate annotated declaration, so reusing the original callback for another test
does not share its exclusions.

With ``pytest-xdist``, worker crashes are retried only after workers confirm their
exclusion declarations reached shared storage. If that storage is unavailable,
worker crashes remain final instead of risking a retry of an excluded test.

Global Configuration
~~~~~~~~~~~~~~~~~~~~

.. py:data:: DD_SERVICE

   The service name reported by default for pytest traces.

   This option is the standard `DD_SERVICE` environment variable.

   Default: Name of the repository being tested, otherwise ``"test"`` if the repository name cannot be found.
"""
