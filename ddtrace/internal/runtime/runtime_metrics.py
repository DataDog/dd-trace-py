# The ddtrace bootstrap (ddtrace-run or ddtrace.auto) sets up the OpenTelemetry meter provider that exports the
# runtime metrics, once the application imports OpenTelemetry.
_BOOTSTRAP_MODULE = "ddtrace.bootstrap.preload"
# opentelemetry-sdk 1.16.0 is the first version whose _init_metrics() accepts the resource of that meter provider, which
# requires an OTLP exporter 1.15.0 or higher.
_OTEL_API_MINIMUM_VERSION = (1, 16, 0)
_OTEL_SDK_MINIMUM_VERSION = (1, 16, 0)
_OTLP_EXPORTER_MINIMUM_VERSION = (1, 15, 0)
_OTLP_METRICS_EXPORTERS = {
    "grpc": "opentelemetry-exporter-otlp-proto-grpc",
    "http/protobuf": "opentelemetry-exporter-otlp-proto-http",
}
_OTLP_RUNTIME_METRICS_MODULE = "ddtrace.internal.runtime.otlp_runtime_metrics"


def _can_export_otlp_runtime_metrics() -> bool:
    """Whether ddtrace sets up an OpenTelemetry meter provider that can export the runtime metrics over OTLP.

    This requires the ddtrace bootstrap, and the OpenTelemetry API, SDK and OTLP exporter of the configured protocol.
    It reads the installed distributions instead of importing OpenTelemetry, which ddtrace only sets up once the
    application imports it.
    """
    if _BOOTSTRAP_MODULE not in sys.modules:
        log.warning(
            "Runtime metrics are sent to DogStatsD: use ddtrace-run or import ddtrace.auto to export them over OTLP."
        )
        return False

    from ddtrace.internal.packages import get_version_for_package
    from ddtrace.internal.settings._opentelemetry import otel_config
    from ddtrace.internal.utils.version import parse_version

    protocol = otel_config.exporter.METRICS_PROTOCOL
    exporter = _OTLP_METRICS_EXPORTERS.get(protocol)
    if exporter is None:
        log.warning(
            "Runtime metrics are sent to DogStatsD: exporting them over OTLP requires the grpc or http/protobuf "
            "protocol, not %r.",
            protocol,
        )
        return False

    for distribution, minimum_version in (
        ("opentelemetry-api", _OTEL_API_MINIMUM_VERSION),
        ("opentelemetry-sdk", _OTEL_SDK_MINIMUM_VERSION),
        (exporter, _OTLP_EXPORTER_MINIMUM_VERSION),
    ):
        version = get_version_for_package(distribution)
        if not version or parse_version(version) < minimum_version:
            log.warning(
                "Runtime metrics are sent to DogStatsD: exporting them over OTLP requires %s %s or higher "
                "(installed: %s).",
                distribution,
                ".".join(str(x) for x in minimum_version),
                version or "none",
            )
            return False
    return True


def _start_otlp_runtime_metrics(_opentelemetry: ModuleType) -> None:
    """Report the runtime metrics through the OpenTelemetry metrics API once the application imports OpenTelemetry.

    This is also when ddtrace sets up the OpenTelemetry meter provider. Importing OpenTelemetry before the application
    does would load it before the application can patch it, for instance with gevent, and the ddtrace bootstrap could
    unload it.
    """
    try:
        from . import otlp_runtime_metrics

        otlp_runtime_metrics.start()
    except Exception:
        log.warning("Failed to report runtime metrics through OpenTelemetry", exc_info=True)


def _stop_otlp_runtime_metrics() -> None:
    ModuleWatchdog.unregister_module_hook("opentelemetry", _start_otlp_runtime_metrics)
    otlp_runtime_metrics = sys.modules.get(_OTLP_RUNTIME_METRICS_MODULE)
    if otlp_runtime_metrics is not None:
        otlp_runtime_metrics.stop()


class RuntimeWorker(periodic.PeriodicService):
    """Worker thread for collecting and writing runtime metrics to a DogStatsd client.

    When OpenTelemetry metrics are enabled, the runtime metrics are reported through the OpenTelemetry metrics API
    instead, once the application imports OpenTelemetry, and no worker thread is started.
    """

    enabled = False
    _instance: Optional[RuntimeWorker] = None
    # Whether the runtime metrics are reported through the OpenTelemetry metrics API, instead of by _instance.
    _otlp = False
    _lock = Lock()

    def __init__(self, interval: float = DEFAULT_RUNTIME_METRICS_INTERVAL, dogstatsd_url: Optional[str] = None) -> None:
        super().__init__(interval=interval)
        self.dogstatsd_url: Optional[str] = dogstatsd_url
        self._dogstatsd_client: DogStatsd = get_dogstatsd_client(self.dogstatsd_url or agent_config.dogstatsd_url)
        # The identity the collector baselines belong to. Read before RuntimeMetrics() seeds them,
        # so a refresh that lands before the callback below is registered shows up as a mismatch
        # in flush() instead of being missed.
        self._collectors_runtime_id: str = get_runtime_id()
        self._runtime_metrics: RuntimeMetrics = RuntimeMetrics()
        # A MicroVM /run transition rotates the runtime ID mid-process without a fork, so the
        # collectors' in-flight interval (CPU time, ctx switches, wall clock, GC pause window)
        # would otherwise mix pre- and post-refresh activity into one sample. Only register this
        # for MicroVMs tagging runtime-id: everyone else keeps a single identity for their
        # lifetime and pays nothing extra.
        self._identity_refresh_enabled = in_aws_lambda_microvm() and config._runtime_metrics_runtime_id_enabled
        # Serializes the refresh callback's reset with flush(). The shared runtime-identity lock
        # keeps the process-wide ID stable while flush snapshots its tags and collectors.
        self._identity_refresh_lock = forksafe.Lock() if self._identity_refresh_enabled else None
        # DogStatsD reads constant_tags separately for each metric, so serialize a MicroVM payload
        # while it is sent. Unlike the identity locks, refresh does not acquire this lock.
        self._send_lock = forksafe.Lock() if self._identity_refresh_enabled else None
        if self._identity_refresh_enabled:
            on_runtime_identity_refresh(self._on_identity_refresh)
            forksafe.register(self._on_fork)
        if EXPERIMENTAL_FEATURES.RUNTIME_METRICS in config._experimental_features_enabled:
            # Enables sending runtime metrics as gauges (instead of distributions with a new metric name)
            self.send_metric = self._dogstatsd_client.gauge
        else:
            self.send_metric = self._dogstatsd_client.distribution

        self._platform_tags = self._collect_platform_tags()

        self._process_tags: list[str] = list(ProcessTags())
        # Only dd.internal.entity_id needs preserving here: service/env/version are already
        # refreshed fresh every flush via TracerTags(), so keeping them too would risk sending a
        # stale value alongside the current one.
        entity_id_prefix = ENTITY_ID_TAG_NAME + ":"
        self._client_constant_tags: list[str] = [
            tag for tag in (self._dogstatsd_client.constant_tags or []) if tag.startswith(entity_id_prefix)
        ]

    @classmethod
    def disable(cls) -> None:
        with cls._lock:
            if cls._otlp:
                _stop_otlp_runtime_metrics()
                cls._otlp = False
            elif cls._instance is None:
                return
            else:
                cls._instance.stop()
                # DEV: Use timeout to avoid locking on shutdown. This seems to be
                # required on some occasions by Python 2.7. Deadlocks seem to happen
                # when some functionalities (e.g. platform.architecture) are used
                # which end up calling
                #    _execute_child (/usr/lib/python2.7/subprocess.py:1023)
                # This is a continuous attempt to read:
                #    _eintr_retry_call (/usr/lib/python2.7/subprocess.py:125)
                # which is the eventual cause of the deadlock.
                cls._instance.join(1)
                cls._instance = None
            cls.enabled = False
            core.root.set_item(RUNTIME_METRICS_ENABLED_KEY, False)

    @classmethod
    def enable(
        cls,
        dogstatsd_url: Optional[str] = None,
    ) -> None:
        with cls._lock:
            if cls._instance is not None or cls._otlp:
                return

            if config._otel_metrics_enabled and _can_export_otlp_runtime_metrics():
                log.debug("Runtime metrics will be exported over OTLP once the application imports OpenTelemetry")
                gc_at_fork.record()
                ModuleWatchdog.after_module_imported("opentelemetry")(_start_otlp_runtime_metrics)
                cls._otlp = True
            else:
                runtime_worker = cls(DEFAULT_RUNTIME_METRICS_INTERVAL, dogstatsd_url)
                runtime_worker.start()
                cls._instance = runtime_worker
                # Over OTLP, the OpenTelemetry SDK collects the runtime metrics a last time when it shuts down at exit:
                # disabling them at exit could happen first and drop them.
                atexit.register(cls.disable)

            cls.enabled = True
            core.root.set_item(RUNTIME_METRICS_ENABLED_KEY, True)

    def stop(self, *args: Any, **kwargs: Any) -> None:
        super().stop(*args, **kwargs)
        self._runtime_metrics.stop()
        if self._identity_refresh_enabled:
            remove_runtime_identity_refresh(self._on_identity_refresh)
            forksafe.unregister(self._on_fork)

    def _on_fork(self) -> None:
        # A fork rotates the runtime ID without an identity refresh. The collectors reseed in their
        # own fork hooks, but forksafe logs and skips a failing hook, so reset again here rather than
        # assume they succeeded: if this raises too, the mismatch stays and the child's first flush
        # retries. Runs after _runtime_id's fork hook (registered at import), so this reads the
        # child's ID.
        self._reset_collectors(get_runtime_id())

    def _on_identity_refresh(self, runtime_id: str) -> None:
        # MicroVM only (see __init__): discard the pre-refresh interval so the next flush's
        # CPU time, context switches, wall clock, and GC pause window cover only activity that
        # happened under the new runtime identity.
        if self._identity_refresh_lock is None:
            return

        with self._identity_refresh_lock:
            if runtime_id == self._collectors_runtime_id:
                # flush() saw the new ID first and already reset for it: resetting again would
                # discard post-refresh activity.
                return
            self._reset_collectors(runtime_id)

    def _reset_collectors(self, runtime_id: str) -> None:
        self._runtime_metrics.reset()
        # Only after reset() returns: a partial reset keeps the mismatch so flush() retries it.
        self._collectors_runtime_id = runtime_id

    def flush(self) -> None:
        if self._identity_refresh_lock is None:
            self._flush_unlocked(self._runtime_metrics)
            return

        # Keep metric collection and the explicit identity transition mutually exclusive. The
        # ordering is lifecycle lock then worker lock everywhere: refresh_identity() invokes this
        # worker's callback while holding the lifecycle lock. Send outside both locks: a blocked
        # DogStatsD socket must not delay a /run identity refresh.
        with runtime_identity_lock():
            with self._identity_refresh_lock:
                runtime_id = get_runtime_id()
                if runtime_id != self._collectors_runtime_id:
                    # The refresh callback was missed (worker created mid-refresh) or failed; either
                    # way the baselines predate this identity.
                    try:
                        self._reset_collectors(runtime_id)
                    except Exception:
                        # Raising would stop the periodic thread; the mismatch stays, so the next
                        # flush retries.
                        log.debug("Failed to reset runtime metric collectors", exc_info=True)
                    # Skip this flush either way: a just-reset interval is too short to report, and a
                    # failed reset would send pre-refresh baselines under the new runtime-id.
                    return
                platform_tags = self._collect_platform_tags()
                self._platform_tags = platform_tags
                if get_runtime_id() != runtime_id:
                    # Defensive: refresh_identity() can't rotate the ID here (it holds the lifecycle
                    # lock), but a rotation outside it could. Don't pair new-ID tags with old
                    # baselines; the next flush resets.
                    return
                # RuntimeCollectorsIterable is lazy. Materialize before releasing the locks so a
                # refresh cannot reset its collectors while this sample is being collected.
                runtime_metrics = list(self._runtime_metrics)

        self._flush_unlocked(runtime_metrics, platform_tags)

    def _flush_unlocked(
        self, runtime_metrics: Iterable[tuple[str, MetricValue]], platform_tags: Optional[list[str]] = None
    ) -> None:
        if self._send_lock is not None:
            with self._send_lock:
                self._send_metrics(runtime_metrics, platform_tags)
            return

        self._send_metrics(runtime_metrics, platform_tags)

    def _send_metrics(
        self, runtime_metrics: Iterable[tuple[str, MetricValue]], platform_tags: Optional[list[str]]
    ) -> None:
        if platform_tags is None:
            platform_tags = self._platform_tags
        runtime_tags = self._format_tags(TracerTags()) + platform_tags + self._process_tags
        # Re-add dd.internal.entity_id on every flush, deduping in case it also arrives via
        # TracerTags() (e.g. a DD_TAGS=dd.internal.entity_id:... workaround).
        constant_tags = list(dict.fromkeys(self._client_constant_tags + runtime_tags))
        log.debug("Sending runtime metrics with the following tags: %s", constant_tags)
        self._dogstatsd_client.constant_tags = constant_tags

        with self._dogstatsd_client:
            for key, value in runtime_metrics:
                log.debug("Sending ddtrace runtime metric %s:%s", key, value)
                self.send_metric(key, value)

    def _collect_platform_tags(self) -> list[str]:
        if config._runtime_metrics_runtime_id_enabled:
            return self._format_tags(PlatformTagsV2())
        return self._format_tags(PlatformTags())

    def _format_tags(self, tags: RuntimeCollectorsIterable[tuple[str, str]]) -> list[str]:
        # DEV: ddstatsd expects tags in the form ['key1:value1', 'key2:value2', ...]
        return [f"{k}:{v}" for k, v in tags]

    periodic = flush
    on_shutdown = flush
