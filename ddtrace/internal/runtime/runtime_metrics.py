T = TypeVar("T", bound=Union[tuple[str, object], str])


class RuntimeCollectorsIterable(Generic[T]):
    ENABLED: Optional[set[str]]
    COLLECTORS: list[type[ValueCollector[T]]]

    def __init__(self, enabled: Optional[set[str]] = None) -> None:
        self._enabled = enabled or self.ENABLED
        # Initialize the collectors.
        self._collectors = [c() for c in self.COLLECTORS]

    def __iter__(self) -> Iterator[T]:
        collected = (collector.collect(self._enabled) for collector in self._collectors)
        return itertools.chain.from_iterable(values for values in collected if values is not None)

    def stop(self) -> None:
        for collector in self._collectors:
            collector.stop()

    def reset(self) -> None:
        for collector in self._collectors:
            collector.reset()

    def __repr__(self) -> str:
        return f"{self.__class__.__name__}(enabled={self._enabled})"


